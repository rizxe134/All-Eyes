const NAMES: Record<string, string> = {
  'ship-cargo': 'CARGO',
  'ship-tanker': 'TANKER',
  'ship-pax': 'PASSENGER',
  'ship-fish': 'FISHING',
  'ship-mil': 'MILITARY',
  'ship-tug': 'TUG',
  'ship-sail': 'SAILING',
  'ship-unk': 'VESSEL',
}

export function classifyShip(shipType: number): { sprite: string; name: string } {
  let sprite = 'ship-unk'
  if (shipType >= 70 && shipType <= 79) sprite = 'ship-cargo'
  else if (shipType >= 80 && shipType <= 89) sprite = 'ship-tanker'
  else if ((shipType >= 60 && shipType <= 69) || (shipType >= 40 && shipType <= 49)) sprite = 'ship-pax'
  else if (shipType === 30) sprite = 'ship-fish'
  else if (shipType === 35) sprite = 'ship-mil'
  else if (shipType === 36 || shipType === 37) sprite = 'ship-sail'
  else if (shipType === 31 || shipType === 32 || shipType === 33 || shipType === 50 || shipType === 52 || shipType === 53 || shipType === 54) sprite = 'ship-tug'
  return { sprite, name: NAMES[sprite] ?? 'VESSEL' }
}
